package main

// weekly runs the scheduled job of spec section 14.2 for every configured
// repo: resolve main at the week's start and end, diff them with the same
// engine, attribute changed nodes to merged MRs through the cached per-MR
// deltas, lay out the package diagram with pinned positions, and publish
// the Structure/Week-YYYY-WW wiki page with a cross-repo roll-up.
//
// It expects wiring.go (main thread) to provide:
//
//	type weeklyRepo struct {
//	    Slug       string          // "group/svc", the repo id used in cache keys
//	    Dir        string          // local checkout with main fetched
//	    Branch     string          // default "main"
//	    Project    gitlab.Project  // the repo's project, for the MR list
//	    ProjectURL string
//	}
//	type weeklyDepsT struct {
//	    Repos      []weeklyRepo
//	    Client     *gitlab.Client   // nil in --dry-run
//	    WikiProject gitlab.Project  // the central "structure" project
//	    Graphs     cache.Store
//	    Deltas     cache.Store
//	    LayoutDir  string           // where <slug>.layout.json files live
//	    Extract    func(ctx context.Context, repoDir, sha string) (*graph.Document, error)
//	    Delta      func(base, head *graph.Document) (*delta.Delta, error)
//	    KeyParts   pipeline.KeyParts
//	}
//	func weeklyDeps(reposFile string, dryRun bool) (weeklyDepsT, error)
//
// reposFile is a YAML list of repos (slug, dir, branch, project, url).

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"shapediff/internal/cache"
	"shapediff/internal/delta"
	"shapediff/internal/graph"
	"shapediff/internal/pipeline"
	"shapediff/internal/weekly"
)

func init() {
	register(command{name: "weekly", short: "run the weekly structure job: per-repo delta, attribution, pinned layout, wiki page", run: runWeekly})
}

func runWeekly(args []string) error {
	fs := flag.NewFlagSet("weekly", flag.ContinueOnError)
	reposFile := fs.String("repos", "repos.yml", "YAML list of repos to cover")
	when := fs.String("week", "", "any date in the week to report (YYYY-MM-DD); default: last week")
	out := fs.String("o", "", "write the page markdown here as well as (or instead of, with --dry-run) the wiki")
	dryRun := fs.Bool("dry-run", false, "do not publish; print the page")
	if err := fs.Parse(args); err != nil {
		return err
	}
	ref := time.Now().UTC().AddDate(0, 0, -7)
	if *when != "" {
		t, err := time.Parse("2006-01-02", *when)
		if err != nil {
			return fmt.Errorf("--week: %w", err)
		}
		ref = t
	}
	start, end := weekly.WeekWindow(ref)
	title := weekly.PageTitle(ref)

	wd, err := weeklyDeps(*reposFile, *dryRun)
	if err != nil {
		return err
	}
	ctx := context.Background()
	var sections []string
	var rows []weekly.RollupRow
	for _, r := range wd.Repos {
		rw, err := weeklyRepoWeek(ctx, wd, r, start, end)
		if err != nil {
			fmt.Fprintf(os.Stderr, "shapediff weekly: %s: %v\n", r.Slug, err)
			sections = append(sections, fmt.Sprintf("## %s\n\nNot reported this week: %v\n\n", r.Slug, err))
			continue
		}
		sections = append(sections, weekly.Page(rw))
		rows = append(rows, weekly.RollupRowFor(rw))
	}
	var page strings.Builder
	fmt.Fprintf(&page, "# %s\n\nWeek %s to %s (UTC). Generated by shapediff %s.\n\n", title, start.Format("2006-01-02"), end.Format("2006-01-02"), Version)
	page.WriteString("## Roll-up\n\n")
	page.WriteString(weekly.Rollup(rows))
	page.WriteString("\n")
	for _, s := range sections {
		page.WriteString(s)
	}
	if *out != "" {
		if err := os.WriteFile(*out, []byte(page.String()), 0o644); err != nil {
			return err
		}
	}
	if *dryRun || wd.Client == nil {
		if *out == "" {
			fmt.Print(page.String())
		}
		return nil
	}
	if _, err := wd.Client.UpsertWikiPage(ctx, wd.WikiProject, title, page.String()); err != nil {
		return fmt.Errorf("publish wiki page: %w", err)
	}
	fmt.Fprintf(os.Stderr, "shapediff weekly: published %s\n", title)
	return nil
}

func weeklyRepoWeek(ctx context.Context, wd weeklyDepsT, r weeklyRepo, start, end time.Time) (weekly.RepoWeek, error) {
	branch := r.Branch
	if branch == "" {
		branch = "main"
	}
	rw := weekly.RepoWeek{Repo: r.Slug, ProjectURL: r.ProjectURL, Branch: branch, Start: start, End: end}
	baseSHA, headSHA, err := weekly.ResolveWeek(ctx, r.Dir, branch, start, end)
	if err != nil {
		return rw, err
	}
	rw.BaseSHA, rw.HeadSHA = baseSHA, headSHA
	base, err := weeklyGraph(ctx, wd, r, baseSHA)
	if err != nil {
		return rw, fmt.Errorf("base %s: %w", baseSHA, err)
	}
	head, err := weeklyGraph(ctx, wd, r, headSHA)
	if err != nil {
		return rw, fmt.Errorf("head %s: %w", headSHA, err)
	}
	d, err := wd.Delta(base, head)
	if err != nil {
		return rw, err
	}
	d.Repo, d.BaseSHA, d.HeadSHA = r.Slug, baseSHA, headSHA
	rw.Delta = d

	if wd.Client != nil && r.Project != "" {
		mrs, err := wd.Client.ListMergedMRs(ctx, r.Project, start, end)
		if err != nil {
			rw.Warnings = append(rw.Warnings, "merged MR list unavailable: "+err.Error())
		}
		for _, mr := range mrs {
			rw.MRs = append(rw.MRs, weekly.MergedMR{IID: mr.IID, Title: mr.Title, WebURL: mr.WebURL, SHA: mr.SHA})
		}
	}
	rw.Attribution = weekly.Attribute(d, rw.MRs, func(iid int, sha string) (*delta.Delta, bool) {
		b, ok, err := wd.Deltas.Get(ctx, cache.MRKey(r.Slug, iid, sha))
		if err != nil || !ok {
			return nil, false
		}
		tmp := filepath.Join(os.TempDir(), fmt.Sprintf("shapediff-mr%d.json", iid))
		if err := os.WriteFile(tmp, b, 0o600); err != nil {
			return nil, false
		}
		defer os.Remove(tmp)
		md, err := delta.ReadFile(tmp)
		return md, err == nil
	})

	layoutPath := filepath.Join(wd.LayoutDir, strings.ReplaceAll(r.Slug, "/", "__")+".layout.json")
	layout, err := weekly.LoadLayout(layoutPath, r.Slug)
	if err != nil {
		rw.Warnings = append(rw.Warnings, "layout: "+err.Error())
		layout, _ = weekly.LoadLayout(filepath.Join(os.TempDir(), "none"), r.Slug)
	}
	nodes, edges := weekly.PackageDiagramInputs(d, graph.NewIndex(head))
	rw.Layout = layout.Render(ctx, nodes, edges)
	if rw.Layout.Warning == "" {
		if err := os.MkdirAll(wd.LayoutDir, 0o755); err == nil {
			if err := layout.Save(layoutPath); err != nil {
				rw.Warnings = append(rw.Warnings, "save layout: "+err.Error())
			}
		}
	}
	if len(rw.Layout.SVG) > 0 {
		svgPath := filepath.Join(wd.LayoutDir, strings.ReplaceAll(r.Slug, "/", "__")+"-"+start.Format("2006-01-02")+".svg")
		if err := os.WriteFile(svgPath, rw.Layout.SVG, 0o644); err == nil {
			rw.Warnings = append(rw.Warnings, "diagram SVG written to "+svgPath+"; upload it and set the page image link")
		}
	}
	return rw, nil
}

func weeklyGraph(ctx context.Context, wd weeklyDepsT, r weeklyRepo, sha string) (*graph.Document, error) {
	key := cache.Key{Repo: r.Slug, SHA: sha, ExtractorVersion: wd.KeyParts.Version, Toolchain: wd.KeyParts.Toolchain, BuilderMode: wd.KeyParts.BuilderMode, ConfigHash: wd.KeyParts.ConfigHash}.String()
	if b, ok, err := wd.Graphs.Get(ctx, key); err == nil && ok {
		if g, err := graph.Read(strings.NewReader(string(b))); err == nil {
			return g, nil
		}
	}
	wt, err := pipeline.AddWorktree(ctx, r.Dir, sha)
	if err != nil {
		return nil, err
	}
	defer wt.Remove()
	g, err := wd.Extract(ctx, wt.Dir, sha)
	if err != nil {
		return nil, err
	}
	if b, err := g.Marshal(); err == nil {
		_ = wd.Graphs.Put(ctx, key, b)
	}
	return g, nil
}
